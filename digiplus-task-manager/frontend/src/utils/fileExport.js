/**
 * Helper to download structured summary as a clean Markdown or text file.
 */
export function downloadSummaryAsFile(item, customFilename) {
  const sourceType = (item.source_type || 'Meeting').replace('_', ' ').toUpperCase()
  const dateStr = item.created_at ? new Date(item.created_at).toLocaleString() : new Date().toLocaleString()
  const author = item.author || 'Team Member'
  const filename = customFilename || `${(item.source_type || 'meeting')}_summary_${new Date().toISOString().slice(0, 10)}.md`

  const decisionsList = (item.decisions && item.decisions.length > 0)
    ? item.decisions.map((d) => `- ${d}`).join('\n')
    : '- No key decisions recorded.'

  const actionItemsList = (item.action_items && item.action_items.length > 0)
    ? item.action_items
        .map((ai) => `- [${ai.status || 'Open'}] **${ai.description}** (Assigned to: ${ai.owner || 'Unassigned'} | Due: ${ai.due_date || 'None'})`)
        .join('\n')
    : '- No action items recorded.'

  const markdownContent = `# ${sourceType} SUMMARY
**Date:** ${dateStr}
**Author / Submitter:** ${author}
${item.filename ? `**Source File:** ${item.filename}\n` : ''}
---

## Executive Summary
${item.summary || 'Summary not provided.'}

---

## Key Decisions
${decisionsList}

---

## Action Items & Tasks
${actionItemsList}

---
*Generated by DigiPlus Task Manager*
`

  const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

